
-- TABLA USUARIOS
CREATE TABLE USUARIOS (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    APELLIDO VARCHAR2(100) NOT NULL,
    CORREO VARCHAR2(150) NOT NULL,
    CONTRASENA VARCHAR2(255) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_USUARIOS
        PRIMARY KEY (ID_USUARIO),

    CONSTRAINT UQ_USUARIOS_CORREO
        UNIQUE (CORREO),

    CONSTRAINT CK_USUARIOS_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);


-- TABLA ROLES
CREATE TABLE ROLES (
    ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(80) NOT NULL,
    DESCRIPCION VARCHAR2(250),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_ROLES
        PRIMARY KEY (ID_ROL),

    CONSTRAINT UQ_ROLES_NOMBRE
        UNIQUE (NOMBRE),

    CONSTRAINT CK_ROLES_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);


-- TABLA PERMISOS
CREATE TABLE PERMISOS (
    ID_PERMISO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(250),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_PERMISOS
        PRIMARY KEY (ID_PERMISO),

    CONSTRAINT UQ_PERMISOS_NOMBRE
        UNIQUE (NOMBRE),

    CONSTRAINT CK_PERMISOS_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);


-- RELACIÓN USUARIOS - ROLES
CREATE TABLE USUARIOS_ROLES (
    ID_USUARIO NUMBER NOT NULL,
    ID_ROL NUMBER NOT NULL,
    FECHA_ASIGNACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_USUARIOS_ROLES
        PRIMARY KEY (ID_USUARIO, ID_ROL),

    CONSTRAINT FK_UR_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO)
        ON DELETE CASCADE,

    CONSTRAINT FK_UR_ROL
        FOREIGN KEY (ID_ROL)
        REFERENCES ROLES (ID_ROL)
        ON DELETE CASCADE
);


-- RELACIÓN ROLES - PERMISOS
CREATE TABLE ROLES_PERMISOS (
    ID_ROL NUMBER NOT NULL,
    ID_PERMISO NUMBER NOT NULL,
    FECHA_ASIGNACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_ROLES_PERMISOS
        PRIMARY KEY (ID_ROL, ID_PERMISO),

    CONSTRAINT FK_RP_ROL
        FOREIGN KEY (ID_ROL)
        REFERENCES ROLES (ID_ROL)
        ON DELETE CASCADE,

    CONSTRAINT FK_RP_PERMISO
        FOREIGN KEY (ID_PERMISO)
        REFERENCES PERMISOS (ID_PERMISO)
        ON DELETE CASCADE
);


